package services
import java.security.MessageDigest // Provides hashing algorithms
import java.security.SecureRandom // Used for generating random salt
import java.util.Base64 // Converts binary data into readable strings

class AuthService {
    val databaseService = DatabaseService()

    /**
     * Verifies whether the supplied email and password match a user record
     * stored in the database.
     *
     * The stored password salt is retrieved and combined with the supplied
     * password before hashing and comparing against the stored hash.
     *
     * @param email The user's email address.
     * @param password The user's plain text password entered during login.
     * @return True if the credentials match, otherwise false.
     */
    fun validateLogin(
        email: String,
        password: String,
    ): Boolean {
        val user = databaseService.findUser(email) // Load user from databsed

        if (user != null && verifyPassword(password, user.passwordKey, user.passwordHash)) {
            return true
        }
        return false
    }

    /**
     * Generates a random salt to be appended to the given password to strengthen
     * password hashing security of the user's data.
     *
     * A secure random value is generated for each byte in a 16 byte array and
     * is then encoded to Base64 string representation to store in the database.
     *
     * @return The generated salt as a Base64 string.
     */
    fun generateSalt(): String {
        val random = SecureRandom() // Create secure random number generator
        val saltBytes = ByteArray(16) // Create array to hold random data
        random.nextBytes(saltBytes) // Fill array with random bytes

        return Base64.getEncoder().encodeToString(saltBytes) // Convert binary to text
    }

    /**
     * Takes the given plain text password, appends the generated salt
     * and hashes the password. The hashed result is returned.
     *
     * An instance of the SHA-256 hashing algorithm is created. The salt
     * and plain text password are then concatenated, converted to bytes, and
     * hashed. The hash is then encooded into Base64 string representation.
     *
     * @param password The user's plain text password entered during login.
     * @param salt The salt generated by generateSalt().
     * @return The password hash as a Base64 string.
     */
    fun hashPassword(
        password: String,
        salt: String,
    ): String {
        val digest = MessageDigest.getInstance("SHA-256") // Create a SHA-256 hashing object

        val combined = password + salt
        val hashBytes = digest.digest(combined.toByteArray()) // convert combined string to bytes and hash
        val encoded = Base64.getEncoder().encodeToString(hashBytes) // convert binary hash to readable text

        return encoded
    }

    /**
     * Takes the given plain text password and the stored salt for that user, 
     * hashes the password, and checks if the generated hash matches the stored
     * hash in the database.
     *
     * The function calls hashPassword(), passing the given password and the stored salt
     * stored in the database. The output of this function is then compared against the
     * user's stored password hash.
     *
     * @param password The user's plain text password entered during login.
     * @param passwordKey The salt originally generated by generateSalt().
     * @param passwordHash The stored hash that was created by hashPassword() upon registration.
     * @return True if the generated hash matches the stored hash, false if not.
     */
    fun verifyPassword(
        password: String,
        passwordKey: String,
        passwordHash: String,
    ): Boolean {
        val newHash = hashPassword(password, passwordKey) // Recreate hash using the same password and key
        return newHash == passwordHash // Return if it is equal to what is stored
    }

    /**
     * Registers a new user using the supplied details.
     *
     * The function validates the entered name, email address, and password before
     * creating the account. Validation ensure the name is not blank, the email
     * address countains both '@' and '.', and the password is at least 8
     * characters long.
     * 
     * If validation passes, a random salt is generated using generateSalt()
     * and the password is hashed using hashPassword(). A User data class is then
     * created and passed to createUser() in DatabaseService.kt for storage.
     * 
     * Fields such as gender, age, height, and weight are initally stored as null as
     * they are optional values that may be updated later.
     *
     * @param name The user's name.
     * @param email The user's email address.
     * @param password The user's plain text password entered during registration.
     * @param accountType True if the user is a personal trainer, false if not.
     * @return The created user's unique ID if successful, -1 if not or validation fails.
     */
    fun registerUser(
        name: String,
        email: String,
        password: String,
        accountType: Boolean,
    ): Int {
        // Validation checks for users
        if (name.isBlank() || !email.contains("@") || !email.contains(".") || password.isBlank() || password.length < 8) return -1
        val key = generateSalt()
        val hash = hashPassword(password, key)

        val user =
            DatabaseService.User(
                0,
                name,
                email,
                hash,
                key,
                null,
                null,
                null,
                null,
                accountType,
            )

        return databaseService.createUser(user) // Function in DatabaseService.kt to store user in database
    }
}
